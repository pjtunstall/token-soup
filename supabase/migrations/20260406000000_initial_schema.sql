DROP TABLE IF EXISTS public.messages CASCADE;
DROP TABLE IF EXISTS public.chats CASCADE;
DROP TABLE IF EXISTS public.roles CASCADE;

CREATE TABLE IF NOT EXISTS public.roles (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    name text NOT NULL,
    description text,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_updated timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT roles_user_id_name_unique UNIQUE (user_id, name)
);

CREATE TABLE IF NOT EXISTS public.chats (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid() NOT NULL,
    title text DEFAULT 'New Chat', -- Request title suggestion on first completion
    created_at timestamptz NOT NULL DEFAULT now(),
    last_updated timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.messages (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    chat_id bigint REFERENCES public.chats(id) ON DELETE CASCADE NOT NULL,
    role_id bigint REFERENCES public.roles(id) ON DELETE SET NULL,
    
    sender_name text NOT NULL,
    sender_type text CHECK (sender_type IN ('user', 'bot')) NOT NULL,
    sender_model text CONSTRAINT check_model_on_bot CHECK (
        (sender_type = 'bot' AND sender_model IS NOT NULL) OR 
        (sender_type = 'user' AND sender_model IS NULL)
    ),
    
    reasoning text CONSTRAINT check_reasoning_on_user CHECK (
        (sender_type = 'user' AND reasoning IS NULL) OR 
        (sender_type = 'bot')
    ),
    
    content text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_messages_chat_id ON public.messages(chat_id);

COMMENT ON TABLE public.chats IS 'Chats per user.';
COMMENT ON TABLE public.messages IS 'Messages per chat.';
COMMENT ON TABLE public.roles IS 'System prompts created by users, representing roles/characters for the LLM to play.';