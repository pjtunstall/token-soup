-- Canonical app schema (edit this file). Apply with: npm run db:apply-schema
-- Rebuilds the entire `public` schema (all objects in it are dropped; data is lost).
--
-- ## Permission model (keep in sync with production; do not rely on dashboard-only changes)
--
-- The Go API uses DATABASE_URL with a direct Postgres connection (see backend/.env.example: usually role
-- `postgres`). JWT auth is validated in Go via SUPABASE_JWKS_URL — not via Postgres roles `anon` or
-- `authenticated`. The browser does not use PostgREST / Data API against these tables, so we do not
-- grant `anon`, `authenticated`, or `service_role` on `public` app objects (least privilege).
--
-- If DATABASE_URL uses a different role, GRANT the same privileges to that role here.
-- supabase_admin is platform-managed and not referenced below.
--
-- Row Level Security: not enabled here. If you add RLS and expose tables via PostgREST later, add
-- policies and extend GRANTs to the API roles as needed.
--
-- SQL grants: comments on each block below. ACL reference: https://www.postgresql.org/docs/current/ddl-priv.html

-- Nukes everything in `public` (tables, views, functions, indexes, …). Other schemas (e.g. auth.*)
-- are untouched. If you later put non-app objects in `public` (extensions, extra tables), move them
-- or switch to targeted drops instead of CASCADE.
DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public AUTHORIZATION postgres;

-- Backend pool role must reference `public` (PostgREST API roles intentionally omitted — see header).
GRANT USAGE ON SCHEMA public TO postgres;

CREATE TABLE public.roles (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    name text NOT NULL,
    description text NOT NULL CHECK (length(trim(description)) > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    last_updated timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT roles_user_id_name_unique UNIQUE (user_id, name)
);

CREATE TABLE public.chats (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid() NOT NULL,
    title text DEFAULT 'New Chat', -- Request title suggestion on first completion
    created_at timestamptz NOT NULL DEFAULT now(),
    last_updated timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.messages (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    chat_id bigint REFERENCES public.chats(id) ON DELETE CASCADE NOT NULL,
    role_id bigint REFERENCES public.roles(id) ON DELETE SET NULL,
    
    sender_name text NOT NULL,
    sender_type text CHECK (sender_type IN ('user', 'bot')) NOT NULL,
    sender_model text CONSTRAINT check_model_on_bot CHECK (
        (sender_type = 'bot' AND sender_model IS NOT NULL) OR 
        (sender_type = 'user' AND sender_model IS NULL)
    ),
    
    reasoning text CONSTRAINT check_reasoning_on_user CHECK (
        (sender_type = 'user' AND reasoning IS NULL) OR 
        (sender_type = 'bot')
    ),
    
    content text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_messages_chat_id ON public.messages(chat_id);

COMMENT ON TABLE public.chats IS 'Chats per user.';
COMMENT ON TABLE public.messages IS 'Messages per chat.';
COMMENT ON TABLE public.roles IS 'System prompts created by users, representing roles/characters for the LLM to play.';

-- ---------------------------------------------------------------------------
-- Existing objects in `public` (tables, sequences, routines) — not “future” objects; see next block.
-- ---------------------------------------------------------------------------
GRANT ALL ON ALL TABLES IN SCHEMA public TO postgres;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO postgres;
GRANT ALL ON ALL ROUTINES IN SCHEMA public TO postgres;

-- Objects created later by `postgres` in `public` inherit the same pattern.
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  GRANT ALL ON TABLES TO postgres;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  GRANT ALL ON SEQUENCES TO postgres;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
  GRANT ALL ON ROUTINES TO postgres;
